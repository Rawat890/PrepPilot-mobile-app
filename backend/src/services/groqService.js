import Groq from 'groq-sdk';

const getGroqClient = () => {
  const apiKey = process.env.GROQ_API_KEY;
  if (!apiKey || apiKey === 'gsk_your_groq_api_key_here') {
    return null;
  }
  return new Groq({ apiKey });
};

export const generateMockQuestionsWithGroq = async ({ category, topic, difficulty = 'Medium', count = 5 }) => {
  const groq = getGroqClient();

  if (!groq) {
    // Fallback realistic questions if GROQ_API_KEY is not configured yet
    return Array.from({ length: count }, (_, idx) => ({
      category,
      topic,
      difficulty,
      questionText: `[Sample AI Mode] In ${category} (${topic}), which principle best applies to scenario #${idx + 1}?`,
      options: [
        `Primary ${topic} Rule A`,
        `Secondary ${topic} Theorem B`,
        `Optimal ${topic} Approach C`,
        `Standard ${topic} Exception D`,
      ],
      correctOptionIndex: idx % 4,
      explanation: `Configure GROQ_API_KEY in backend/.env to generate live Groq LLM questions. Option ${String.fromCharCode(65 + (idx % 4))} is correct based on core ${topic} fundamentals.`,
      isAiGenerated: true,
    }));
  }

  const prompt = `Generate ${count} multiple-choice exam questions for category "${category}", topic "${topic}", difficulty "${difficulty}".
Return ONLY a valid JSON object with a single key "questions" containing an array of objects.
Each object must strictly have:
- "questionText": string
- "options": array of exactly 4 strings
- "correctOptionIndex": integer (0, 1, 2, or 3)
- "explanation": clear 2-3 sentence step-by-step explanation of why the correct option is right.`;

  const completion = await groq.chat.completions.create({
    model: process.env.GROQ_MODEL || 'llama-3.3-70b-versatile',
    messages: [
      {
        role: 'system',
        content: 'You are an expert competitive exam question creator. Always output strict valid JSON without markdown fences.',
      },
      { role: 'user', content: prompt },
    ],
    temperature: 0.6,
    response_format: { type: 'json_object' },
  });

  const rawContent = completion.choices[0]?.message?.content || '{"questions":[]}';
  const parsed = JSON.parse(rawContent);
  const questions = Array.isArray(parsed.questions) ? parsed.questions : [];

  return questions.map((q) => ({
    category,
    topic,
    difficulty,
    questionText: q.questionText,
    options: Array.isArray(q.options) && q.options.length === 4 ? q.options : ['Option A', 'Option B', 'Option C', 'Option D'],
    correctOptionIndex: typeof q.correctOptionIndex === 'number' ? q.correctOptionIndex : 0,
    explanation: q.explanation || 'Detailed explanation generated by Groq AI.',
    isAiGenerated: true,
  }));
};

export const generateAiExplanationWithGroq = async ({ questionText, options, correctOptionIndex, userSelectedIndex }) => {
  const groq = getGroqClient();
  const correctAnswer = options[correctOptionIndex];
  const userAnswer = userSelectedIndex !== null && userSelectedIndex !== undefined ? options[userSelectedIndex] : 'Unanswered';

  if (!groq) {
    return `Correct Answer: ${correctAnswer}.

Step-by-Step Breakdown:
1. Identify the core concept tested in the question.
2. "${correctAnswer}" directly satisfies all conditions.
3. Add your GROQ_API_KEY in backend/.env for personalized Groq AI tutoring.`;
  }

  const prompt = `Explain this exam question clearly to a student:
Question: ${questionText}
Options: ${options.map((opt, i) => `${i + 1}. ${opt}`).join(' | ')}
Correct Answer: ${correctAnswer}
Student Selected: ${userAnswer}

Provide:
1. Why the correct answer is right (concise & clear).
2. Why the student's choice was incorrect (if they answered wrong) or a quick tip to remember this concept.`;

  const completion = await groq.chat.completions.create({
    model: process.env.GROQ_MODEL || 'llama-3.3-70b-versatile',
    messages: [
      {
        role: 'system',
        content: 'You are a concise, encouraging exam tutor. Keep explanations structured and easy to read on mobile.',
      },
      { role: 'user', content: prompt },
    ],
    temperature: 0.5,
    max_tokens: 450,
  });

  return completion.choices[0]?.message?.content || 'Explanation unavailable.';
};
